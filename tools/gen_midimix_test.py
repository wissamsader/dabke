# writes DABKE's tests/midimix.txt: every control of the MIDImix, one by one, and its lights (the tracks' layout)
import sys
BASE = [16, 20, 24, 28, 46, 50, 54, 58]
PARTS = ["lead", "drone", "left hand", "bass line", "kick", "darbuka and tabl", "claps", "riq and sagat"]
NAMES = ["LEAD", "DRONE", "LEFT HAND", "BASS LINE", "KICK", "DARBUKA + TABL", "CLAPS", "RIQ + SAGAT"]
VOL = [0, 4, 1, 2, 43, 42, 44, 45]            # the parts' volumes (dabke.h P_*)
FILTER, SEND, PITCH = 47, 63, 71
L = []
w = L.append
def press(n, t=30):
    w(f"midi 90 {n:02X} 7F"); w(f"midi 80 {n:02X} 7F"); w(f"wait {t}")
def cc(c, v, par=None, exp=None, t=30):
    w(f"midi B0 {c:02X} {v:02X}"); w(f"wait {t}")
    if par: w(f"expect {par} {exp}")
w("# Every control of the Akai MIDImix, one by one (made by a script, tools/gen_midimix_test.py; the numbers are the")
w("# MIDImix's factory ones), and its lights. The eight strips are DABKE's eight tracks: fader its volume, top knob its")
w("# effect (delay and reverb), middle knob its filter, bottom knob its pitch, MUTE it off and on. A fader or a knob")
w("# never picks its track: it moves its own strip's track whatever the keys play, and the screen says what moved, once")
w("# it is plain that one control moved alone (\"TRACK 6: VOLUME 70\"), without changing the page. REC ARM is REC for its")
w("# track and picks it (it records when let go, again stops at once, held a second its last take goes). The master")
w("# fader is the scene fader; SOLO is HOLD; BANK the rhythms (both together: the top sound cleared). No light blinks:")
w("# each shows what its label says. In step mode a strip's knob moved with a step held is locked on that step; a knob")
w("# of the recording track is kept as locks on the steps the recording passes.")
def pick(t):                                    # SEL held and the t-th white key: that track picked
    w("press SEL"); w(f"tapkey w{t-1}"); w("release SEL"); w("wait 30"); w(f"expect track {t}")
w("#   ../../fm1-dabke/app/build/host/dabke_host ../../fm1-dabke/app/tests/midimix.txt OUTDIR")
w("wait 900")
w("expect track 0")
w("# SEND ALL: the 33 control changes (16..31, 46..62) in one burst, no note: all of them taken, every light sent, no")
w("# track picked, nothing said")
w("out"); w("listen")
for c in list(range(16, 32)) + list(range(46, 63)): w(f"midi B0 {c:02X} 40")
w("wait 200")
w("unsaid TRACK")
for par, e in ([(f"par{VOL[i]}", 50) for i in range(8)] + [(f"par{SEND+i}", 50) for i in range(8)] +
               [(f"par{FILTER+i}", 0) for i in range(8)] + [(f"par{PITCH+i}", 0) for i in range(8)] +
               [("maqam", 2), ("root", 2), ("master", 64), ("track", 0), ("top_mask", 0)]):
    w(f"expect {par} {e}")
for pkt in ("90 01 00", "90 16 00", "90 03 00", "90 18 00", "90 19 00", "90 1A 00", "90 1B 00"): w(f"expect_out USB {pkt}")
w("# the scene fader down (no top sound yet: nothing changes)")
cc(62, 0, "master", 0)
for i, p in enumerate(PARTS):
    w(""); w(f"# strip {i+1}: fader (CC {BASE[i]+3}) its volume, top knob (CC {BASE[i]}) its effect, middle (CC {BASE[i]+1})")
    w(f"# its filter, bottom (CC {BASE[i]+2}) its pitch (quarter tones: 48 an octave). No track is picked by them. One of them")
    w("# moved alone is said a moment later, and said on as it moves; the page stays (here: the sound page)")
    for v, e in ((0x7F, 100), (0x00, 0), (0x40, 50)): cc(BASE[i] + 3, v, f"par{VOL[i]}", e)
    for v, e in ((0x7F, 100), (0x00, 0), (0x40, 50)): cc(BASE[i], v, f"par{SEND+i}", e)
    for v, e in ((0x7F, 50), (0x00, -50), (0x40, 0)): cc(BASE[i] + 1, v, f"par{FILTER+i}", e)
    for v, e in ((0x7F, 48), (0x00, -48), (0x40, 0)): cc(BASE[i] + 2, v, f"par{PITCH+i}", e)
    w("wait 300"); w("expect track 0")
    w("tap ENV"); w("wait 30"); w("listen")
    cc(BASE[i] + 3, 0x59, f"par{VOL[i]}", 70, 200); w(f"said TRACK {i+1}: VOLUME 70")
    cc(BASE[i] + 3, 0x40, f"par{VOL[i]}", 50); w(f"said TRACK {i+1}: VOLUME 50")
    w("wait 300"); cc(BASE[i] + 1, 0x20, f"par{FILTER+i}", -25, 200); w(f"said TRACK {i+1}: FILTER DARK 50")
    cc(BASE[i] + 1, 0x40, f"par{FILTER+i}", 0); w(f"said TRACK {i+1}: FILTER OPEN")
    w("wait 300"); cc(BASE[i], 0x59, f"par{SEND+i}", 70, 200); w(f"said TRACK {i+1}: EFFECT 70")
    cc(BASE[i], 0x40, f"par{SEND+i}", 50)
    w("expect track 0"); w("expect page 3"); w("tap HOME"); w("wait 300")
w(""); w("# the bottom knob, the track's pitch: its middle (CC 60 to 67) in tune; FULL (as it starts) whole semitones, an")
w("# octave either way at its ends; said in words")
w("listen")
cc(26, 0x3C, "par73", 0); cc(26, 0x43, "par73", 0)
cc(26, 0x3B, "par73", -4, 200); w("said TRACK 3: DOWN 1")
cc(26, 0x50, "par73", 12); w("said TRACK 3: UP 3")
w("# MICRO (PITCH STEPS, the effects page's row 4, K3): quarter tones")
w("tap FX"); w("wait 30"); w("turn SELECT -20"); w("turn SELECT 3"); w("wait 30"); w("expect row 3")
w("turn K3 1"); w("wait 30"); w("expect ch44 1"); w("tap HOME"); w("wait 30")
cc(26, 0x3B, "par73", -1, 200); w("said TRACK 3: DOWN A QUARTER")
cc(26, 0x50, "par73", 10); w("said TRACK 3: UP 2 AND A HALF")
cc(26, 0x40, "par73", 0); w("said TRACK 3: IN TUNE")
w("tap FX"); w("wait 30"); w("turn K3 -1"); w("wait 30"); w("expect ch44 0"); w("tap HOME"); w("wait 30")
w("# a note sounding moves with the knob: the drone silent (its fader down), the left hand picked (SEL held and the")
w("# third white key), its fader up, D held (293.7 Hz); the knob up 5: 392 Hz; then up 3: 349 Hz")
cc(23, 0x00, "par4", 0); w("wait 150"); cc(27, 0x66); w("wait 150"); w("expect track 0"); pick(3)
w("key 9 down"); w("wait 400"); w("expect pitch_x10 >2900"); w("expect pitch_x10 <2975")
cc(26, 0x5B, "par73", 20, 300); w("expect pitch_x10 >3870"); w("expect pitch_x10 <3970")
cc(26, 0x50, "par73", 12, 300); w("expect pitch_x10 >3450"); w("expect pitch_x10 <3530")
w("key 9 up"); cc(26, 0x40, "par73", 0); cc(23, 0x40, "par4", 50); cc(27, 0x40); w("wait 600")

w(""); w("# the master fader, the scene fader. At its top (its last 3 %) a control moved sets that control's top value, not")
w("# the sound as set; anywhere else the sound as set; between, the fader goes from the one to the other")
w("listen")
cc(62, 0x7F, "master", 127); w("said FADER UP: THIS IS THE TOP SOUND")
cc(16, 0x7F); w("expect par63 50"); w("expect top0 100"); w("expect eff63 100")
cc(19, 0x00); w("expect par0 50"); w("expect top3 0"); w("expect eff0 0"); w("expect top_mask 9")
cc(26, 0x7F); w("expect par73 0"); w("expect top10 48"); w("expect eff73 48"); w("expect top_mask 1033")
cc(62, 0x00, "master", 0); w("said FADER DOWN: THE SOUND AS SET")
w("expect eff63 50"); w("expect eff0 50"); w("expect eff73 0")
cc(62, 0x40, "master", 64)
w("expect eff63 75"); w("expect eff0 25"); w("expect eff73 24")
w("# below the top, a knob moves the sound as set; the fader still goes towards the top")
cc(16, 0x20); w("expect par63 25"); w("expect top0 100"); w("expect eff63 63")
w("# BANK LEFT and RIGHT together: the top sound cleared (the rhythm stays)")
w("midi 90 19 7F"); w("midi 90 1A 7F"); w("wait 30"); w("midi 80 19 7F"); w("midi 80 1A 7F"); w("wait 30")
w("expect top_mask 0"); w("expect rhythm 0"); w("said TOP SOUND CLEARED")
w("expect eff63 25"); w("expect eff0 50")
cc(62, 0x00, "master", 0)
cc(16, 0x40, "par63", 50)
w("expect track 3"); pick(1)

w(""); w("# MUTE 1-8: each part off and on again; its light lit while it is muted, dark again; after each change every")
w("# light is sent again")
w("listen")
for i, p in enumerate(PARTS):
    n = 1 + 3 * i
    w(f"# MUTE {i+1} (note {n}): {p}")
    w("out"); press(n, 80); w(f"expect mute {1 << i}"); w("expect track 1")
    w(f"expect_out USB 90 {n:02X} 7F")
    o = 1 + 3 * ((i + 1) % 8)
    w(f"expect_out USB 90 {o:02X} 00")
    w("out")
    press(n); w("expect mute 0")
    w(f"expect_out USB 90 {n:02X} 00")
w("# nothing muted, nothing on: every light dark")
w("expect mixleds 0")
w("# every 2 s every light again, unchanged")
w("out"); w("wait 2100")
for pkt in ("90 01 00", "90 03 00", "90 19 00", "90 1B 00"): w(f"expect_out USB {pkt}")

w(""); w("# REC ARM 1 (note 3): pressed, nothing records yet (its light dark); let go, the lead records, its light lit; the")
w("# first key starts the rhythm; again: it stops at once")
w("out"); w("midi 90 03 7F"); w("wait 200"); w("expect rec_track -1"); w("expect_no_out USB 90 03 7F"); w("expect track 1")
w("midi 80 03 7F"); w("wait 30")
w("expect rec_track 0"); w("expect rec_waiting 1"); w("said TRACK 1: PLAY TO START")
w("expect_out USB 90 03 7F")
w("tapkey 7"); w("tapkey 9"); w("wait 30"); w("expect running 1"); w("expect rec_waiting 0")
w("out"); press(3); w("expect rec_track -1"); w("expect trk_n0 2"); w("expect trk_takes0 1"); w("expect_out USB 90 03 00")
w("said TRACK 1: 1 BAR, 1 TAKE")
w("# again: a second take over it")
press(3); w("expect rec_track 0"); w("expect overdub 1"); w("tapkey 11"); w("wait 60")
press(3); w("expect rec_track -1"); w("expect trk_n0 3"); w("expect trk_takes0 2")
w("# REC ARM 1 held a second: the last take gone, and nothing records (the screen never says RECORDING, its light stays")
w("# dark); held again: the one before, the lead empty")
w("listen"); w("out")
w("midi 90 03 7F"); w("wait 600"); w("expect rec_track -1"); w("wait 500"); w("midi 80 03 7F"); w("wait 30")
w("expect rec_track -1"); w("expect trk_n0 2"); w("expect trk_takes0 1"); w("said TRACK 1: LAST TAKE GONE")
w("expect_no_out USB 90 03 7F")
w("midi 90 03 7F"); w("wait 1100"); w("midi 80 03 7F"); w("wait 30")
w("expect trk_n0 0"); w("expect trk_len0 0"); w("said TRACK 1 EMPTY")
w("# one track records at a time: REC ARM 4 (the bass line, note 12), then REC ARM 2 (the drone, note 6) takes over")
w("out"); press(12); w("expect rec_track 3"); w("said TRACK 4: RECORDING")
w("tapkey 0"); w("wait 30")
w("out"); press(6); w("expect rec_track 1"); w("expect_out USB 90 06 7F"); w("expect_out USB 90 0C 00")
w("expect trk_n3 1"); w("expect trk_key3_0 29")
w("tapkey 9"); w("wait 30")
press(6); w("expect rec_track -1"); w("expect trk_n1 1"); w("expect trk_key1_0 62")
w("# REC ARM 5 (the kick, note 15): it picks track 5 and records its drum live, each hit kept on the step it falls on")
w("# (the track his from the first one); again: it stops; held a second: that take gone, the rhythm's own steps again")
w("out"); press(15); w("expect rec_track 4"); w("expect track 5"); w("said TRACK 5: RECORDING"); w("expect_out USB 90 0F 7F")
w("tapkey 2"); w("wait 30"); w("expect dedit 16"); w("expect his4 1"); w("expect drum_take 5")
w("out"); press(15); w("expect rec_track -1"); w("said TRACK 5: TAKE KEPT"); w("expect_out USB 90 0F 00")
w("midi 90 0F 7F"); w("wait 1100"); w("midi 80 0F 7F"); w("wait 30")
w("expect rec_track -1"); w("expect dedit 0"); w("said TRACK 5: BACK TO THE RHYTHM")
w("# held a second again, nothing of his on the track: said, and nothing changes")
w("listen"); w("midi 90 0F 7F"); w("wait 1100"); w("midi 80 0F 7F"); w("wait 30")
w("expect rec_track -1"); w("expect dedit 0"); w("said TRACK 5: NOTHING OF YOURS HERE"); w("unsaid RECORDING")
w("tap PLAY"); w("wait 90"); w("expect running 0")

w(""); w("# SOLO (note 27) is HOLD. The lead picked (SEL held and the first white key); a key down, SOLO: that note held")
w("# (SOLO's light lit), it sounds on when the key is let go and its key stays lit; a key played over it is not held")
cc(19, 0x66); w("wait 150"); w("expect track 5"); pick(1)
w("key 7 down"); w("wait 30")
w("out"); press(27); w("expect hold 1"); w("expect held_n 1"); w("said HOLD: 1 NOTE"); w("expect_out USB 90 1B 7F")
w("key 7 up"); w("wait 100"); w("expect voices0 1"); w("expect lit_key7 1")
w("tapkey 14"); w("wait 100"); w("expect held_n 1"); w("expect voices0 1")
w("# SOLO again with another key down: that one held instead")
w("key 11 down"); w("wait 30"); press(27); w("expect held_n 1"); w("said HOLD: 1 NOTE")
w("key 11 up"); w("wait 100"); w("expect voices0 1"); w("expect lit_key11 1"); w("expect lit_key7 0")
w("# SOLO with no key down: let go, SOLO dark")
w("out"); press(27); w("expect hold 0"); w("expect held_n 0"); w("said HOLD OFF"); w("expect_out USB 90 1B 00")
w("wait 100"); w("expect voices0 0")
w("# BANK RIGHT / LEFT (notes 26, 25): the rhythm")
press(26); w("expect rhythm 1")
press(25); w("expect rhythm 0")
w("# PLAY: the BANK lights stay dark")
w("out"); w("tap PLAY"); w("wait 1000"); w("expect running 1"); w("expect_no_out USB 90 19 7F"); w("expect_no_out USB 90 1A 7F")
w("tap PLAY"); w("wait 90"); w("expect running 0")
w("expect mute 0")

w(""); w("# ---- step mode (SEQ on the FM-1), the lead picked. A step held (the third white key) and a strip's knob moved:")
w("# that knob's value locked on that step, the knob itself as it was. Strip 1's middle knob (its filter, CC 17), then")
w("# strip 2's (CC 21: another track's knob, locked on the lead's step all the same; no track is picked by it), then")
w("# strip 1's fader (CC 19, its volume) and its bottom knob (CC 18, its pitch)")
cc(19, 0x66); w("wait 150"); w("expect track 1")
w("tap SEQ"); w("wait 60"); w("expect seq 1"); w("listen")
w("key w2 down"); w("wait 30")
cc(17, 0x20); w("expect lock0_2_47 -25"); w("expect par47 0"); w("expect locks 1")
cc(21, 0x7F); w("expect lock0_2_48 50"); w("expect par48 0"); w("wait 150"); w("expect track 1")
cc(19, 0x00); w("expect lock0_2_0 0"); w("expect par0 80")
cc(18, 0x50); w("expect lock0_2_71 12"); w("expect par71 0"); w("expect locks 4")
w("# the master fader with a step held: it cannot be locked: said once, and it does not move")
cc(62, 0x40); w("expect master 0"); w("said FADE CANNOT BE LOCKED TO A STEP")
w("key w2 up"); w("wait 60")
w("# a hold in which a knob was turned is no tap: nothing was added to the step; its key shows the second level")
w("expect trig0_2 0"); w("expect mid_key4 1"); w("expect lit_key4 0")
w("# the rhythm running: the lock holds from its step (the filter as the engine has it: -0.5) and lets go at the bar's")
w("# end, with nothing of the lead's to end it sooner: a lock only step, held to the next of the same knob")
w("tap PLAY"); w("wait 400"); w("expect epar47 -500"); w("expect lk_at47 -25"); w("expect epar0 0")
w("tap PLAY"); w("wait 90"); w("expect running 0"); w("expect epar47 0"); w("expect epar0 800"); w("expect lk_at47 -999")
w("# SOLO in step mode is HOLD too; a strip's knob with no step held is the knob itself (its own track's, said), and")
w("# the track picked stays picked")
w("key 1 down"); w("wait 30"); w("out"); press(27); w("expect hold 1"); w("expect_out USB 90 1B 7F")
w("key 1 up"); w("wait 30"); press(27); w("expect hold 0")
w("wait 300"); w("listen")
cc(21, 0x20, None, None, 200); w("expect par48 -25"); w("expect track 1"); w("expect locks 4"); w("said TRACK 2: FILTER DARK 50")
cc(21, 0x40); w("expect par48 0"); w("expect track 1"); w("said TRACK 2: FILTER OPEN")
w("# EDIT with the step held: its locks removed")
w("key w2 down"); w("wait 30"); w("tap EDIT"); w("wait 30"); w("key w2 up"); w("wait 60")
w("expect locks 0"); w("said STEP 3: LOCKS REMOVED"); w("expect hold 0")
w("tap SEQ"); w("wait 60"); w("expect seq 0")

w(""); w("# ---- a knob of the recording track is kept as locks: REC ARM 1 (the rhythm stopped: the first key starts it), a")
w("# note, then strip 1's middle knob swept while it records: locks on the steps passed, the knob's own value as it")
w("# was; its fader moved: never kept. Recording over: the sweep comes back with the loop. REC ARM 1 held a second:")
w("# the take gone, and its locks with it")
press(3); w("expect rec_track 0"); w("tapkey 7"); w("wait 60"); w("expect running 1")
cc(17, 0x30, None, None, 110); cc(17, 0x20, None, None, 110); cc(17, 0x10, None, None, 110)
w("expect par47 0"); w("expect locks0 >1"); w("expect epar47 <-300")
cc(19, 0x40); w("expect par0 50"); w("expect lock0_0_0 -999")
press(3); w("expect rec_track -1"); w("expect trk_takes0 1"); w("expect locks0 >1")
w("wait 900"); w("expect par47 0")
w("midi 90 03 7F"); w("wait 1100"); w("midi 80 03 7F"); w("wait 60")
w("expect trk_n0 0"); w("expect locks0 0"); w("said TRACK 1 EMPTY")
w("tap PLAY"); w("wait 90"); w("expect running 0"); w("expect epar47 0")
w("# nothing blinked: with the rhythm running no light was sent but for a change (the BANK lights never)")
w("out"); w("tap PLAY"); w("wait 1900"); w("expect_no_out USB 90 19 7F"); w("expect_no_out USB 90 1A 7F")
w("expect_no_out USB 90 03 7F"); w("expect_no_out USB 90 01 7F"); w("expect_no_out USB 90 1B 7F")
w("tap PLAY"); w("wait 90"); w("expect running 0")
w("leds")
open(sys.argv[1], "w").write("\n".join(L) + "\n")
