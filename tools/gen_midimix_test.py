def press(n, t=30):
    w(f"midi 90 {n:02X} 7F"); w(f"midi 80 {n:02X} 7F"); w(f"wait {t}")
def cc(c, v, par=None, exp=None, t=30):
    w(f"midi B0 {c:02X} {v:02X}"); w(f"wait {t}")
    if par: w(f"expect {par} {exp}")
